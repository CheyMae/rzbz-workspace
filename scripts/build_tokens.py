"""design/tokens.figma.json -> src/styles/tokens.css (CSS custom properties, light + dark)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
t = json.loads((ROOT / "design/tokens.figma.json").read_text())


def var(name):
    return "--" + name.lower().replace("/", "-")


light = [f"  {var(k)}: {v['Light']};" for k, v in t["semantics"].items()]
dark = [f"  {var(k)}: {v['Dark']};" for k, v in t["semantics"].items()]
fixed = [f"  --scale-{k}: {v}px;" for k, v in t["scale"].items()]
fixed += [f"  --radius-{k}: {v}px;" for k, v in t["radius"].items()]
fixed += [f"  --border-{k}: {v}px;" for k, v in t["borderWidth"].items()]
type_rules = []
for k, s in t["type"].items():
    fam = "'Grandstander', cursive" if s["family"] == "Grandstander" else "'Figtree', system-ui, sans-serif"
    fixed.append(f"  --type-{k}: {s['weight']} {s['size']}px/{s['line']}px {fam};")
    type_rules.append(f".t-{k} {{ font: var(--type-{k}); }}")

css = ["/* Generated by scripts/build_tokens.py from design/tokens.figma.json. Do not edit by hand. */",
       ":root {", *fixed, *light, "  color-scheme: light;", "}",
       "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {",
       *["  " + l for l in dark], "    color-scheme: dark;", "  }", "}",
       ":root[data-theme=\"dark\"] {", *dark, "  color-scheme: dark;", "}", "", *type_rules, ""]
out = ROOT / "src/styles/tokens.css"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(css))
print(f"wrote {out.relative_to(ROOT)}: {len(t['semantics'])} colors, {len(t['type'])} type styles")
